"""timers-gen's stale-pair detection.

WHY THIS IS A TEST AND NOT A COMMENT. Three unit pairs were renamed on
2026-10-13 (`pazras-memory` -> `familiar-memory`, and the same for
`journal-index` and `healthcheck`). The generator copied the new pairs and said
nothing about the old ones: `--check` compared only CURRENT entries and `apply`
copied only current entries, so the retired pair sat in the dotfiles — and
stayed enabled — until it was removed by hand. A stale pair is
indistinguishable from a live one to stow and to systemd, so nothing else would
have reported it, and the next rename would have repeated it.

The hazard is one-sided: nothing breaks loudly, and the machine runs the job
twice. So the mechanism is tested here rather than trusted.

The three properties, in the order they matter:
  1. `--check` NAMES a stale pair and exits 3, so the drift is visible.
  2. `--apply-dotfiles --yes` REMOVES it.
  3. A hand-maintained unit in the same directory is never touched — the
     generator only removes files carrying its own banner.
"""
from __future__ import annotations

import os
import pathlib
import subprocess

import pytest

REPO = pathlib.Path(__file__).resolve().parents[3]
SCRIPT = REPO / "engine/schedule/timers-gen.sh"
BANNER = "# GENERATED by timers-gen.sh"


def _run(units_dir: pathlib.Path, staging: pathlib.Path, *args: str):
    env = dict(os.environ,
               PAZRAS_DOTFILES_UNITS=str(units_dir),
               PAZRAS_STAGING=str(staging))
    return subprocess.run(["bash", str(SCRIPT), *args], env=env,
                          capture_output=True, text=True, check=False)


@pytest.fixture
def units(tmp_path):
    """A dotfiles unit directory populated by the generator itself, so the
    fixture starts from the state an apply leaves behind."""
    d = tmp_path / "units"
    d.mkdir()
    staging = tmp_path / "staging"
    first = _run(d, staging, "--apply-dotfiles", "--yes")
    assert first.returncode == 0, first.stderr
    assert list(d.glob("*.timer")), "the fixture populated nothing"
    return d, staging


def test_a_clean_tree_reports_no_stale_pair(units):
    d, staging = units
    got = _run(d, staging, "--check")
    assert got.returncode == 0, got.stdout + got.stderr
    assert "no stale pair" in got.stdout


def test_a_renamed_pair_is_reported_and_removed(units):
    """The 2026-10-13 case: the table renamed a key, the old files remain."""
    d, staging = units
    live = sorted(p.stem for p in d.glob("*.timer"))[0]
    for ext in ("timer", "service"):
        (d / f"pazras-retired.{ext}").write_text(
            "# GENERATED by timers-gen.sh — do not hand-edit.\n[Unit]\n")
    # A hand-maintained unit in the same directory: never a rename's business.
    (d / "hand-written.service").write_text("[Unit]\nDescription=mine\n")

    check = _run(d, staging, "--check")
    assert check.returncode == 3, check.stdout + check.stderr
    assert "STALE" in check.stdout and "pazras-retired" in check.stdout
    assert live  # the live pair is not what was reported

    applied = _run(d, staging, "--apply-dotfiles", "--yes")
    assert applied.returncode == 0, applied.stderr
    assert "REMOVED" in applied.stdout and "pazras-retired" in applied.stdout
    assert not (d / "pazras-retired.timer").exists()
    assert not (d / "pazras-retired.service").exists()
    # 3: the hand-written unit survived, and the tree is clean again.
    assert (d / "hand-written.service").exists()
    again = _run(d, staging, "--check")
    assert again.returncode == 0, again.stdout + again.stderr


def test_a_stale_pair_is_reported_even_when_a_current_one_is_missing(units):
    """`--check` reports both kinds at once: a rename in progress leaves a
    missing new pair AND a stale old one, and fixing one must not hide the
    other."""
    d, staging = units
    (d / "pazras-gone.timer").write_text("# GENERATED by timers-gen.sh\n")
    (d / "pazras-gone.service").write_text("# GENERATED by timers-gen.sh\n")
    for p in d.glob("*.service"):
        if p.stem not in ("pazras-gone",):
            p.rename(p.with_suffix(".service.removed"))
    got = _run(d, staging, "--check")
    assert got.returncode == 3
    assert "STALE" in got.stdout and "MISSING" in got.stdout
