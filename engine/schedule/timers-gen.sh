#!/usr/bin/env bash
# pazras-timers-gen — render every calendar-scheduled systemd unit pair from
# the one PAZRAS_TIMERS table in pazras-master-config.sh.
#
# WHY THIS EXISTS. Nine near-identical `pazras-*.{service,timer}` pairs lived
# in the dotfiles stow package, hand-written one at a time as each process was
# added. They drifted the way every hand-copied fact in this system drifts
# (STRUCTURE.md's category table did the same thing before pazras-structure-
# gen.sh): some units had RandomizedDelaySec, some didn't; `pazras-validate.
# service` had no Nice=/IOSchedulingClass= at all, so a validation run could
# compete with interactive work for disk IO while every sibling unit was
# `idle`. None of that was a deliberate choice — it was nine copy-paste
# lineages that each stopped being updated at a different point.
#
# So cadence, jitter, niceness and failure-notification wiring for every
# scheduled process now live in ONE table (PAZRAS_TIMERS, pazras-master-
# config.sh) and these are DERIVED ARTIFACTS — the same governing rule as the
# skill routers and STRUCTURE.md: never hand-edit a rendered unit file, edit
# the table and rerun.
#
# WHAT STAYS OUT OF THIS MECHANISM, DELIBERATELY:
#   notify@.service          the OnFailure= handler every generated unit
#                            points at. Referenced, never generated — it is
#                            not itself scheduled.
#   pazras-archive-flush.*   a Path unit (DirectoryNotEmpty=), not a Timer.
#                            "Scheduled" here means calendar-driven; a path
#                            unit fires on filesystem state instead and has no
#                            OnCalendar= to normalise. Left hand-maintained.
#
# WRITE TARGETS.
#   (default)          renders into $STAGING (inside 06_SYSTEM — always safe
#                       to write; this repo is git-tracked and nothing here
#                       touches the live dotfiles stow source).
#   --check             renders into a throwaway tmpdir and diffs against what
#                       is actually live in the dotfiles canonical source,
#                       reporting drift per unit. Read-only. Exit 3 on drift,
#                       matching familiar structure generate --check.
#   --apply-dotfiles     copies $STAGING into the dotfiles canonical source —
#                       i.e. the user's own stow package. NEVER run this
#                       unattended: dotfiles edits are a sign-off decision,
#                       not a mechanical one (see the dotfiles README / the
#                       agent boundary on that repo). This script will not be
#                       invoked with this flag by an agent without the human
#                       having asked for it in the same turn.
#
# RENAMING A KEY. The table is the truth, so a pair whose key is gone is a stale
# ARTIFACT, not a unit: --check reports it (STALE, exit 3) and --apply-dotfiles
# removes it. Only files carrying BANNER_TIMER below are eligible, so
# hand-maintained units beside them (`notify@.service`,
# `pazras-archive-flush.path`) are never touched.
#
# A removed FILE does not unload a RUNNING unit: systemd keeps a failed stub,
# `list-timers` still shows it, and `is-enabled` says not-found. The order that
# avoids the stub is `systemctl --user disable --now <old>.timer` FIRST, then
# remove; if the file is already gone, `systemctl --user reset-failed <old>.timer`
# clears it. Removed while loaded, three of them sat in `list-timers` for hours
# on 2026-10-13 looking like live timers.
#
# Usage: familiar schedule timers [--check | --apply-dotfiles]
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/../lib/roots.sh"
source "$SCRIPT_DIR/../structure/pazras-config-loader.sh"
load_pazras_config >/dev/null 2>&1 || true

# Both overridable, so the mechanism can be exercised without touching the real
# tree or the user's dotfiles (engine/checks/tests/test_timers_gen.py).
STAGING="${PAZRAS_STAGING:-$PAZRAS_UNITS}"
DOTFILES_UNITS="${PAZRAS_DOTFILES_UNITS:-$HOME/02_AREAS/B_Tech/dotfiles/shared/systemd/.config/systemd/user}"
MODE="${1:-render}"
[[ "$MODE" == "--check" ]] && MODE="check"
[[ "$MODE" == "--apply-dotfiles" ]] && MODE="apply"

BANNER_TIMER="# GENERATED by timers-gen.sh — do not hand-edit.
# Edit PAZRAS_TIMERS in config/structure/pazras-master-config.sh, then run:
#   familiar schedule timers            (stage into ${STAGING#$HOME/})
#   familiar schedule timers --check    (diff staged vs. live, no writes)
# Applying a staged change to this live file is a human sign-off, not a
# mechanical step — see timers-gen.sh header."

render_timer() {   # <unit>
    local u="$1"
    local cal persistent delay desc
    cal=$(get_timer_field "$u" on_calendar)
    persistent=$(get_timer_field "$u" persistent true)
    delay=$(get_timer_field "$u" randomized_delay 15m)
    desc=$(get_timer_field "$u" desc "$u")

    printf '%s\n\n' "$BANNER_TIMER"
    printf '[Unit]\nDescription=%s\n\n[Timer]\n' "$desc"
    printf 'OnCalendar=%s\n' "$cal"
    [[ "$persistent" == "true" ]] && printf 'Persistent=true\n'
    [[ -n "$delay" ]] && printf 'RandomizedDelaySec=%s\n' "$delay"
    printf '\n[Install]\nWantedBy=timers.target\n'
}

render_service() {   # <unit>
    local u="$1"
    local exec_cmd desc nice ioclass notify after success_exit timeout_start extra_path doc path_line

    exec_cmd=$(get_timer_field "$u" exec)
    desc=$(get_timer_field "$u" desc "$u")
    nice=$(get_timer_field "$u" nice 15)
    ioclass=$(get_timer_field "$u" ioclass idle)
    notify=$(get_timer_field "$u" notify true)
    after=$(get_timer_field "$u" after)
    success_exit=$(get_timer_field "$u" success_exit)
    timeout_start=$(get_timer_field "$u" timeout_start)
    extra_path=$(get_timer_field "$u" extra_path)
    doc=$(get_timer_field "$u" doc)

    path_line="%h/bin:%h/.local/bin:/usr/local/bin:/usr/bin:/bin"
    [[ -n "$extra_path" ]] && path_line="${extra_path}:${path_line}"

    printf '%s\n\n' "$BANNER_TIMER"
    printf '[Unit]\nDescription=%s\n' "$desc"
    [[ -n "$doc" ]] && printf 'Documentation=file:%%h/%s\n' "$doc"
    [[ -n "$after" ]] && printf 'After=%s\n' "$after"
    [[ "$notify" == "true" ]] && printf 'OnFailure=notify@%%n.service\n'
    printf '\n[Service]\nType=oneshot\n'
    printf 'Environment=PATH=%s\n' "$path_line"
    printf 'ExecStart=%%h/%s\n' "$exec_cmd"
    [[ -n "$success_exit" ]] && printf 'SuccessExitStatus=%s\n' "$success_exit"
    printf 'Nice=%s\n' "$nice"
    printf 'IOSchedulingClass=%s\n' "$ioclass"
    [[ -n "$timeout_start" ]] && printf 'TimeoutStartSec=%s\n' "$timeout_start"
}

# Unit pairs the generator WROTE and the table no longer configures.
#
# A rename is the case this exists for: 2026-10-13 renamed three `pazras-*`
# pairs to `familiar-*`, and `--check`/`apply` both looked only at CURRENT
# entries, so a stale pair sat in the dotfiles (and stayed enabled) until it was
# removed by hand. A stale pair is indistinguishable from a live one to stow and
# to systemd, so nothing else would have reported it.
#
# Only files carrying the generator's own banner are eligible: hand-maintained
# units in the same directory (`notify@.service`, `pazras-archive-flush.path`,
# anything another tool owns) are never touched.
stale_units() {
    local u stem
    for f in "$DOTFILES_UNITS"/*.timer "$DOTFILES_UNITS"/*.service; do
        [[ -f "$f" ]] || continue
        head -1 "$f" 2>/dev/null | grep -q 'GENERATED by timers-gen.sh' || continue
        stem="$(basename "$f")"
        stem="${stem%.timer}"; stem="${stem%.service}"
        u="$(get_timer_units)"
        if ! printf '%s\n' "$u" | grep -qx "$stem"; then
            printf '%s\n' "$stem"
        fi
    done | sort -u
}

stage() {   # <dir>
    local dir="$1"
    mkdir -p "$dir"
    local u
    for u in $(get_timer_units); do
        render_timer "$u"   > "$dir/${u}.timer"
        render_service "$u" > "$dir/${u}.service"
    done
}

case "$MODE" in
    render)
        stage "$STAGING"
        echo "rendered $(get_timer_units | wc -l) unit pairs into ${STAGING#$HOME/}"
        echo "next: familiar schedule timers --check   (diff against the live dotfiles source)"
        ;;
    check)
        tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
        stage "$tmp"
        drift=0
        for u in $(get_timer_units); do
            for ext in timer service; do
                staged="$tmp/${u}.${ext}"
                live="$DOTFILES_UNITS/${u}.${ext}"
                if [[ ! -f "$live" ]]; then
                    echo "MISSING  ${u}.${ext}  (not present in dotfiles yet)"
                    drift=1
                elif ! diff -q "$staged" "$live" >/dev/null 2>&1; then
                    echo "DRIFT    ${u}.${ext}"
                    drift=1
                fi
            done
        done
        for u in $(stale_units); do
            echo "STALE    ${u}.{timer,service}  (generated, no longer in PAZRAS_TIMERS)"
            drift=1
        done
        if (( drift )); then
            echo
            echo "Run \`diff -u $DOTFILES_UNITS/<unit>.<ext> <(familiar schedule timers && cat $STAGING/<unit>.<ext>)\` to inspect a change."
            echo "Applying to the live dotfiles source is a sign-off decision — see timers-gen.sh header."
            exit 3
        fi
        echo "all $(get_timer_units | wc -l) unit pairs match the live dotfiles source, and no stale pair is left behind."
        ;;
    apply)
        # A second, explicit flag — not just --apply-dotfiles — because this is
        # the one branch of this script that writes into the user's own
        # dotfiles stow package. An agent should never pass --yes on its own
        # initiative; a human running this by hand is not gated by that norm.
        if [[ "${2:-}" != "--yes" ]]; then
            echo "This would copy the staged unit pairs into:" >&2
            echo "  $DOTFILES_UNITS" >&2
            echo "Run \`familiar schedule timers --check\` first to see exactly what changes." >&2
            echo "Re-run with \`familiar schedule timers --apply-dotfiles --yes\` to actually write." >&2
            exit 2
        fi
        [[ -d "$STAGING" ]] || stage "$STAGING"
        n=0
        for u in $(get_timer_units); do
            for ext in timer service; do
                cp "$STAGING/${u}.${ext}" "$DOTFILES_UNITS/${u}.${ext}"
                ((n++))
            done
        done
        echo "wrote $n unit files into $DOTFILES_UNITS"
        removed=0
        for u in $(stale_units); do
            for ext in timer service; do
                [[ -f "$DOTFILES_UNITS/${u}.${ext}" ]] || continue
                rm -f "$DOTFILES_UNITS/${u}.${ext}"
                ((removed++))
            done
            # The FILE is gone; the live unit is not. systemctl is the human's
            # to run -- this script writes the dotfiles and nothing else.
            echo "REMOVED  ${u}.{timer,service} — run: systemctl --user reset-failed ${u}.timer"
            echo "         (the file is already gone, so the unit is a FAILED stub in the"
            echo "          manager until reset-failed; disabling it first avoids that)"
        done
        if (( removed )); then
            echo "cleaned $removed stale unit file(s) the table no longer configures"
        fi
        echo "next: cd $HOME/02_AREAS/B_Tech/dotfiles && git status   (review before committing)"
        echo "then: systemctl --user daemon-reload && systemctl --user enable --now <new-unit>.timer"
        if (( removed )); then
            echo "and:  bash ${DOTFILES_UNITS%%/shared/systemd/*}/bootstrap.sh   (restow, so the removed files leave ~/.config/systemd/user)"
        fi
        ;;
    *)
        echo "usage: familiar schedule timers [--check]" >&2
        exit 1
        ;;
esac
