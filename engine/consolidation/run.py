"""run -- the nightly consolidation pass. Stage order from consolidation-cycle.md.

The order is not arbitrary and must not be reshuffled for convenience: replay
of the day's episodes precedes consolidation into the knowledge tree, which
precedes global downscaling. You cannot distil what has not been ingested, or
prune on a score computed before the distillation that would have raised it.

Each stage is idempotent and may be interrupted; the next run resumes.
"""
from __future__ import annotations

import datetime as dt
import sys

from consolidation import brief, pass_ctx, posture, queue, report
from lib import git, invocation
from lib import roots
from consolidation.stages import aggregate, associate, conflict, consolidate, downscale, label, preflight, recommend, reindex, replay, score
from knowledge import knowledge_index

SPEC = invocation.Spec(
    name="run",
    usage="run [--dry-run] [--verbose] [--no-commit] [--force] [--with-model] "
          "[--with-jev] [--stages=LIST] [--date=YYYY-MM-DD]",
    flags=("--dry-run", "--verbose", "--no-commit", "--force", "--with-model",
           "--with-jev"),
    options=("--stages", "--date"),
    aliases={"-n": "--dry-run", "-v": "--verbose"},
)

# (id, label, callable). A stage suppresses its own writes under --dry-run;
# there is no table-driven gate, because a dry run must still REPORT what it
# would have done and a skipped stage reports nothing. This list is also the
# only source of a stage's name: `main` records it in `ctx.stages_run` once a
# stage returns, so a stage never spells its own label.
STAGES = [
    ("1", "replay",      replay.run),
    ("2", "aggregate",   aggregate.run),
    ("3", "score",       score.run),
    ("4", "consolidate", consolidate.run),   # proposal-only in M2
    ("5", "associate",   associate.run),
    # Same stage id as `associate`, deliberately, and for the reason stage 7 is
    # shared by two generators: both are about RELATIONS BETWEEN LEAVES, and the
    # pass cannot express "run the relation stages" without a number that is not
    # also downscale's. The two are separate callables so one broken relation
    # check cannot take the other down. Proposals and notes from here are
    # labelled `5d` -- `associate` already uses 5a/5b/5c -- so the report's
    # `*(stage 5d)*` lines name which half of 5 spoke, while the run table stays
    # one entry. Renumbering was not an option: it would churn every report that
    # names a stage.
    ("5", "conflicts",   conflict.run),
    ("6", "downscale",   downscale.run),     # proposal-only, always
    # Same stage id as `downscale`, on the precedent stage 5d set: two
    # generators, one run-table entry, and notes labelled `6b` so the report
    # says which of them spoke. They share the id because stage 6 is the
    # PROPOSAL-ONLY stage -- neither of them may write -- and `--stages=6` must
    # mean all of it. Separate callables so one cannot take the other down.
    ("6", "label",       label.run),         # proposal-only, always (3a)
    ("7", "reindex",     reindex.run),
    # Same stage id on purpose: stage 7 is "regenerate the derived indexes",
    # and it has two generators over two populations (skills, knowledge). They
    # share the id so `--stages=7` means all of it and their notes land in one
    # section of the report, and stay separate callables so one broken
    # generator cannot take the other down with it.
    ("7", "knowledge-index", knowledge_index.run),
]


def _fresh(ctx) -> list:
    """Tonight's proposals as queue items, in report order.

    The order here is the order stage 4/5/6 raised them, which is also the order
    `report.render` numbers them -- `by_kind` below sorts by kind, so this must
    too, or ordinal N would name different items in the report and in the queue.
    That is the one invariant `decide` cannot survive losing.
    """
    out = []
    for p in sorted(ctx.proposals, key=lambda p: p.kind):
        out.append(queue.as_dict(p.kind, p.target, p.what, p.why, p.stage,
                                 p.target_kind, ctx.today.isoformat(),
                                 members=p.members))
    return out


def _commit(ctx) -> None:
    """Invariant 4: the pass commits its own work as ONE commit, so a bad night
    is one `git revert`."""
    if not git.status_lines(ctx.repo):
        ctx.log("nothing to commit")
        return
    n = len(ctx.actions)
    msg = (f"memory: nightly consolidation {ctx.today.isoformat()}\n\n"
           f"{n} mechanical repair(s), {len(ctx.proposals)} proposal(s) reported.\n"
           f"Stages: {', '.join(ctx.stages_run)}.\n\n"
           f"Generated by `familiar consolidation run`. Proposals are in the report and\n"
           f"were NOT applied -- see {roots.MEMORY_REL}/journal/reports/.\n")
    r = git.commit(ctx.repo, msg)
    if not r.ok:
        ctx.note("8", f"commit failed: {r.err.strip()[:200]}", "error")


def main(inv) -> int:
    dry = inv.has("--dry-run")
    no_commit = inv.has("--no-commit") or dry
    only = {s.strip() for s in inv.get("--stages").split(",") if s.strip()} or None
    today = dt.date.today()
    if inv.get("--date"):
        try:
            today = dt.date.fromisoformat(inv.get("--date"))
        except ValueError as exc:
            raise invocation.UsageError(f"--date: {exc}")

    ctx = pass_ctx.Pass(inv.agents, inv.base, dry, today,
                        inv.has("--verbose"), flags=inv.flags)
    print(f"familiar consolidation run — {today.isoformat()}"
          f"{' (dry run)' if dry else ''}")

    # Preflight is stage 0 and is not in STAGES -- the pass cannot proceed
    # without it, so it is called directly rather than in the loop. It is
    # recorded on the same terms all the same: only once it has succeeded.
    if preflight.run(ctx):
        ctx.stages_run.append("0 preflight")
    else:
        if not dry:
            print(f"!! aborted: {ctx.aborted}", file=sys.stderr)
            preflight.release()
            # EXIT 0, deliberately. A dirty tree or a held lock is an EXPECTED
            # outcome, not a failure: the pass declines and the next night picks
            # it up. Returning non-zero fires the unit's OnFailure= handler,
            # which writes ~/.cache/pazras-status and raises a desktop
            # notification -- so every night the user had uncommitted work would
            # look like a broken backup. An alert that cries wolf is worse than
            # no alert, because it teaches the user to ignore the channel that
            # also reports real failures.
            return 0 if ctx.aborted and (
                "dirty" in ctx.aborted or "lock" in ctx.aborted) else 2
    # An idle day is skipped outright: no model calls, no report churn, and
    # above all no demotion proposals built on decay the user had no chance to
    # prevent. --force overrides for a deliberate rerun.
    if ctx.quiet and not inv.has("--force"):
        print("  nothing has changed since the last pass — skipping "
              "(--force to run anyway)")
        ctx.note("0", "idle day: no new transcripts, usage lines or commits "
                      "since the last pass. Skipped entirely — no scoring, no "
                      "proposals, no commit.")
        ctx.stages_run.append("(skipped: idle)")
        preflight.release()
        return 0

    try:
        for sid, label, fn in STAGES:
            if only and sid not in only:
                continue
            print(f"  stage {sid} · {label}")
            try:
                fn(ctx)
            except Exception as exc:       # one broken stage must not lose the rest
                ctx.note(sid, f"stage raised {type(exc).__name__}: {exc}", "error")
                print(f"    !! {type(exc).__name__}: {exc}", file=sys.stderr)
                continue                   # a stage that raised did not run
            ctx.stages_run.append(f"{sid} {label}")
        # The posture checks run BEFORE the report is rendered, so their
        # findings land in it and in the brief. They read HISTORY, so what they
        # judge is every pass up to and including last night -- tonight's own
        # commit has not been made yet and is tomorrow's subject. Not a gate:
        # see posture.run for why aborting on a finding is the wrong move.
        posture.run(ctx)
        # THE ORDER HERE IS LOAD-BEARING, and getting it wrong is silent.
        #
        #   1. rebuild the queue from tonight's proposals (`_fresh` + `merge`)
        #   2. band THAT queue (`recommend.run`)
        #   3. render the report from the banded queue
        #
        # Banding before the rebuild (the first version of this) asked about
        # LAST night's item set and then replaced it: the recommendations that
        # survived were the ones whose id happened to persist, and every item
        # NEW tonight was banded nowhere and lost its recommendation in the
        # merge. The symptom was four unbanded items and no cost note, which
        # reads exactly like a skipped call.
        #
        # The queue is written before the report renders because the report
        # prints the queue's digest and `decide` compares that digest (1d);
        # rendering first would print a digest computed from last night's file.
        # A dry run writes nothing, here as everywhere: its queue is dropped, so
        # it cannot make tonight's `decide` refuse.
        if not ctx.dry_run:
            queue.save(ctx.base, queue.merge(queue.items(ctx.base),
                                             _fresh(ctx), ctx.today.isoformat()))
        # Banding is gated -- see stages/recommend.py on why the spend is
        # deliberate. Its notes land in the report rendered below, so the cost
        # line is part of the night's record (2g) rather than only a console.
        try:
            recommend.run(ctx)
        except Exception as exc:
            ctx.note("8b", f"recommendations not computed "
                           f"({type(exc).__name__}: {exc}); the report above is "
                           f"unaffected", "error")
        path = report.write(ctx)
        # Stage 8 emits TWO artifacts for two readers, and the split is the
        # point: the dated report is the human's per-night decision list, the
        # brief is the agent's fixed-path answer to the three questions a
        # session opens with (memory/knowledge/system/consolidation/consolidation-cycle.md). Neither is derivable from the other
        # -- the report is organised by what needs deciding, the brief by what
        # was asked. A brief that fails must not lose the report, so it is
        # guarded like a stage.
        try:
            brief_path = brief.write(ctx)
        except Exception as exc:
            ctx.note("8", f"brief not written ({type(exc).__name__}: {exc}); "
                          f"the report above is unaffected", "error")
            brief_path = None
        ctx.stages_run.append("8 report")
        if not no_commit:
            _commit(ctx)
        preflight.record_run(ctx)
    finally:
        preflight.release()

    print(f"\n  {len(ctx.actions)} change(s), {len(ctx.proposals)} proposal(s), "
          f"{len([n for n in ctx.notes if n.level != 'note'])} warning(s)")
    try:
        shown = path.relative_to(ctx.repo)
    except ValueError:
        shown = path                       # dry-run reports live outside the repo
    print(f"  report: {shown}")
    if brief_path:
        try:
            print(f"  brief:  {brief_path.relative_to(ctx.repo)}")
        except ValueError:
            print(f"  brief:  {brief_path}")
    if dry:
        print("  (dry run — nothing was written to the tree)")
    return 0
