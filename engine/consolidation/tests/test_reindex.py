"""The reindex plan: what would be written, decided without writing it.

Two of these tests cover the only places this module can destroy something a
human wrote -- a hand-written command file it must leave alone, and a stale
generated one it may delete. Both were untestable while the harness homes were
module-level constants pointing at the real `~/.claude`.
"""
import pathlib

import pytest

from consolidation.stages import reindex

TIER0 = """# Skills — Tier 0

<!-- BEGIN:BRANCHES (generated) -->
placeholder
<!-- END:BRANCHES -->

<!-- BEGIN:SCOPES (generated) -->
placeholder
<!-- END:SCOPES -->
"""
GENERATED_CMD = ("---\ndescription: x\n---\n\n"
                 "<!-- GENERATED by `familiar skills index` from "
                 "06_SYSTEM/memory/skills/system/practice/gone/SKILL.md — do not hand-edit. -->\n")


def _skill(root, subject, name, *, invocation="model", trust="trusted", triggers=()):
    """`skills/system/<subject>/<name>/SKILL.md` -- the O6b layout, three levels."""
    p = root / "skills" / "system" / subject / name / "SKILL.md"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(
        "---\n"
        f"name: {name}\n"
        f"description: does {name}\n"
        f"invocation: {invocation}\n"
        f"trust: {trust}\n"
        "origin: authored\n"
        f"triggers: [{', '.join(triggers)}]\n"
        "antitriggers: []\n"
        "related: []\n"
        "---\n\nbody\n")
    return p


@pytest.fixture
def root(tmp_path):
    a = tmp_path / "agents"
    (a / "skills").mkdir(parents=True)
    (a / "skills" / "CONTEXT.md").write_text(TIER0)
    (a / "skills" / "_scope-bindings.md").write_text(
        '---\nbindings: [\n  "06_SYSTEM/** :: system"\n]\n---\n')
    (a / "skills" / "system").mkdir()
    (a / "skills" / "system" / "practice").mkdir()
    (a / "skills" / "system" / "practice" / "_subject.md").write_text(
        "---\nname: practice\ndescend_when: how we work\nblurb: b\nalways_on: []\n---\n")
    _skill(a, "practice", "router-visible", triggers=["alpha"])
    _skill(a, "practice", "human-only", invocation="user")
    _skill(a, "practice", "retired", trust="deprecated", triggers=["beta"])
    return a


@pytest.fixture
def homes(tmp_path):
    claude = tmp_path / "home" / ".claude" / "commands"
    claude.parent.mkdir(parents=True)
    absent = tmp_path / "home" / ".config" / "nothing-here" / "command"
    return [("claude-code", claude, True), ("absent-harness", absent, False)]


# ── planning writes nothing ──────────────────────────────────────────────────

def test_planning_touches_no_file(root, homes):
    before = {p: p.read_text() for p in root.rglob("*.md")}
    p = reindex.plan(root, homes)
    assert p.writes and not p.failed
    assert {q: q.read_text() for q in root.rglob("*.md")} == before


def test_drift_is_the_files_whose_bytes_would_change(root, homes):
    p = reindex.plan(root, homes)
    assert len(p.drift) == len(p.writes), "nothing generated exists yet"
    p.apply()
    assert reindex.plan(root, homes).drift == [], "idempotent on a second run"


def test_apply_returns_what_it_changed(root, homes):
    changed = reindex.plan(root, homes).apply()
    assert (root / "skills" / "TRIGGERS.md") in changed
    assert reindex.plan(root, homes).apply() == []


# ── the user-invoked split ───────────────────────────────────────────────────

def test_a_user_invoked_skill_is_absent_from_every_model_facing_artifact(root, homes):
    reindex.plan(root, homes).apply()
    for generated in ("CONTEXT.md", "TRIGGERS.md", "system/CONTEXT.md",
                      "system/practice/CONTEXT.md"):
        assert "human-only" not in (root / "skills" / generated).read_text()
    assert "human-only" in (root / "skills" / "USER-INVOKED.md").read_text()


def test_a_user_invoked_skill_becomes_a_command_in_each_home_that_exists(root, homes):
    reindex.plan(root, homes).apply()
    claude, absent = homes[0][1], homes[1][1]
    assert (claude / "human-only.md").exists()
    assert "disable-model-invocation: true" in (claude / "human-only.md").read_text()
    assert not absent.exists(), "an absent harness home is skipped, never created"


def test_a_deprecated_skill_keeps_its_row_but_is_never_routed_to(root, homes):
    reindex.plan(root, homes).apply()
    assert "retired" in (root / "skills" / "system" / "practice"
                         / "CONTEXT.md").read_text()
    assert "beta" not in (root / "skills" / "TRIGGERS.md").read_text()


# ── the two destructive paths ────────────────────────────────────────────────

def test_a_hand_written_command_is_left_alone_and_reported(root, homes):
    claude = homes[0][1]
    claude.mkdir(parents=True)
    mine = claude / "human-only.md"
    mine.write_text("# I wrote this by hand\n")
    p = reindex.plan(root, homes)
    p.apply()
    assert mine.read_text() == "# I wrote this by hand\n"
    assert any("not ours, left alone" in prob.what for prob in p.problems)
    assert not p.failed, "a foreign file is a warning, not a failure"


def test_a_generated_command_whose_skill_is_gone_is_stale(root, homes):
    claude = homes[0][1]
    claude.mkdir(parents=True)
    orphan = claude / "gone.md"
    orphan.write_text(GENERATED_CMD)
    p = reindex.plan(root, homes)
    assert orphan in p.stale
    p.apply()
    assert not orphan.exists()


# ── failures are data, not exits ─────────────────────────────────────────────

def test_a_missing_tier0_marker_is_an_error_not_a_SystemExit(root, homes):
    (root / "skills" / "CONTEXT.md").write_text("# no markers here\n")
    p = reindex.plan(root, homes)          # must not raise, must not exit
    assert p.failed and p.writes == []
    assert any("BEGIN:BRANCHES" in prob.what for prob in p.problems)


def test_a_subject_without_prose_writes_nothing_rather_than_losing_it(root, homes):
    (root / "skills" / "system" / "practice" / "_subject.md").unlink()
    p = reindex.plan(root, homes)
    assert p.failed and p.writes == []
    assert any("_subject.md" in prob.what for prob in p.problems)


def test_an_over_budget_tier0_still_regenerates_but_says_so(root, homes, monkeypatch):
    monkeypatch.setattr(reindex, "TIER0_BUDGET", 10)
    p = reindex.plan(root, homes)
    assert not p.failed and p.writes, "a stale router is worse than an oversized one"
    assert any("over the 10 budget" in prob.what for prob in p.problems)


def test_a_skill_without_frontmatter_is_skipped_with_a_warning(root, homes):
    bad = root / "skills" / "system" / "practice" / "broken" / "SKILL.md"
    bad.parent.mkdir()
    bad.write_text("no frontmatter\n")
    p = reindex.plan(root, homes)
    assert not p.failed
    assert any("no frontmatter" in prob.what for prob in p.problems)


def test_a_command_file_from_any_generation_is_ours():
    """R2d renamed the generator's command; files the old name wrote must not
    be orphaned as "not ours" (the BLOCK_ANY lesson)."""
    from consolidation.stages import reindex
    old = "<!-- GENERATED by `pazras-" + "memory skills index` from x"
    assert reindex.OURS.search(old)
    assert reindex.OURS.search(reindex.CMD_BANNER.format(path="x"))
    assert not reindex.OURS.search("hand-written by the user")
