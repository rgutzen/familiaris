"""Stage 7 -- Reindex. Regenerate the skill routers and the trigger index.

Ported from M1's `skills-index.py`, which this replaces (one implementation,
so the reader and the writer cannot drift apart; the original is in git
history at 33ee7f0). Runs
inside the pass and remains callable alone as `familiar skills index`.

GOVERNING RULE (memory-architecture.md): markdown is truth, indexes are
disposable caches. Everything this writes is a DERIVED ARTIFACT rebuilt from
frontmatter. Never hand-edit the output; edit the source and rerun.

Two populations, one source. `invocation: model` skills are indexed by the
routers; `invocation: user` skills are HUMAN ONLY -- excluded from every router
and from TRIGGERS.md, and emitted instead as a slash command in each harness
home (skill-routing.md SS User-invoked skills). A `trust: deprecated` skill stays
visible in its subject router, for provenance, but is never put in TRIGGERS.md.

Idempotency is provable rather than asserted: `--check` rewrites nothing and
exits 3 on drift, which is also how the pass runs it under --dry-run.

ONE PLAN, TWO CALLERS. `plan(root, homes)` decides everything and writes
nothing; `Plan.apply()` writes. `main()` is a CLI adapter over it (healthcheck
runs `skills index --check` and depends on these exit codes), and stage 7 calls
plan/apply directly. It used to reach this module only through `main(argv)`,
which meant mutating module globals for the root and running the whole plan
TWICE -- once with `--check` to learn whether anything had drifted, once to
write -- and even then the count was only printed, so the stage recorded `-1`.

NOTHING HERE EXITS. `replace_block` used to `raise SystemExit` on a missing
marker, and SystemExit is not an `Exception`, so it escaped run.py's per-stage
guard and killed the whole pass before the report was written and before the
nightly commit: one malformed router file cost the entire night. Problems are
data now, and the caller decides how loud they are.

Exit codes: 0 ok - 1 error - 3 --check found drift.
"""
from __future__ import annotations
import argparse, dataclasses, os, re, sys, pathlib

from knowledge.frontmatter import parse as _parse, split_list
from lib import roots

DEFAULT_ROOT = pathlib.Path(os.environ.get("PAZRAS_MEMORY_DIR",
                            str(roots.INSTALL / roots.MEMORY_REL)))
TIER0_BUDGET = 2400            # skill-routing.md §Verification
BRANCH_TAG = "BRANCHES"        # the Tier 0 marker; same name knowledge/CONTEXT.md uses
                             # (`CATEGORIES` until O6b: Tier 0 names branches now)

BANNER = "<!-- GENERATED FILE — do not hand-edit. Rebuild: `familiar skills index` -->"

# Harness command homes. A user-invoked skill becomes one file in each that
# exists; an absent home is skipped, never created beyond the command dir
# itself. Mirrors `engine/boundaries/compile.py`, which emits the same way.
#
#   Claude Code  ~/.claude/commands/<name>.md
#       Commands reach the model only through the SlashCommand tool, and
#       `disable-model-invocation: true` removes them from it. Verified in the
#       binary and in plugin-dev/command-development/frontmatter-reference.md.
#   opencode     ~/.config/opencode/command/<name>.md
#       Globs `{command,commands}/**/*.md` and follows symlinks. It supports
#       NEITHER `disable-model-invocation` NOR `allow_implicit_invocation`
#       (measured: 0 occurrences in 1.18.23) -- which is why user-invoked skills
#       are commands here and not skills: opencode has no way to hide a skill
#       from the model, but it exposes no model-facing command tool either.
HARNESS_COMMANDS = [
    ("claude-code", pathlib.Path.home() / ".claude/commands",          True),
    ("opencode",    pathlib.Path.home() / ".config/opencode/command",  False),
]
# A command file is ours if ANY generation of this generator wrote it -- the
# command was the `pazras-memory` back-end's own until R2d, and the CLI is
# `familiar` since 2026-10-13. Matching only the current spelling would orphan
# every file the previous one wrote: the `BLOCK_ANY` lesson from
# boundaries/compile.py, one generator over.
OURS = re.compile(r"GENERATED by `(?:familiar|pazras-memory) skills index`")
CMD_BANNER = ("<!-- GENERATED by `familiar skills index` from "
              + roots.from_home(roots.MEMORY) + "/{path} — do not hand-edit. -->")


# ── what a plan is ───────────────────────────────────────────────────────
@dataclasses.dataclass
class Problem:
    """Something the caller must decide how loudly to say.

    Same rule as `ledger.py`: this module reports what it found and never picks
    the volume. A foreign command file is a stderr line to the CLI and a report
    note to the pass; neither is this module's call.
    """
    level: str                  # error | warn | note
    what: str
    path: pathlib.Path | None = None


@dataclasses.dataclass
class Plan:
    """Every byte that would be written, decided without writing any of them."""
    root: pathlib.Path
    writes: list                # [(path, content)]
    stale: list                 # generated command files whose skill is gone
    problems: list              # [Problem]
    routed: dict                # (branch, subject) -> [skill fm], model-reachable only
    users: list                 # user-invoked skills
    tier0_chars: int = 0

    @property
    def failed(self) -> bool:
        """An error means the tree cannot be rendered correctly, so nothing is
        written -- exactly what the old `return 1` did, before it could write."""
        return any(p.level == "error" for p in self.problems)

    @property
    def drift(self) -> list:
        """The files whose bytes would actually change. The old code learned
        this by running the whole plan a second time and still recorded `-1`."""
        return [p for p, new in self.writes
                if not p.exists() or p.read_text() != new]

    def apply(self) -> list:
        """Write the drifted files, delete the stale ones. Returns what changed."""
        changed = []
        for path, new in self.writes:
            if not path.exists() or path.read_text() != new:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(new)
                changed.append(path)
        for path in self.stale:
            path.unlink()
            changed.append(path)
        return changed


# ── frontmatter ──────────────────────────────────────────────────────────
# M1 shipped its own parser here. It is now `..frontmatter`, shared with every
# stage that writes: one dialect, one implementation, so the reader and the
# writer cannot drift apart. `split_list` is imported above for the same reason.
def read_frontmatter(path: pathlib.Path) -> dict:
    return _parse(path.read_text()) if path.exists() else {}


def _register():
    """The subject and branch registers, imported late.

    Same contract and the same reason as `knowledge_index._BRANCHES`: a register
    that fails to load is `ontology selfcheck`'s to report, and an import here
    must not be what turns a CLI into a traceback.
    """
    try:
        from knowledge import ontology
        return ontology.BRANCHES, ontology.SUBJECTS
    except Exception:              # noqa: BLE001 - see docstring
        return {}, {}


def load_skills(root: pathlib.Path, problems: list) -> dict[tuple, list[dict]]:
    """(branch, subject) -> [skill frontmatter], each with _name, _path, _user.

    The subject IS the path: `skills/<branch>/<subject>/<name>/SKILL.md`, the
    three branches and subjects of `config/knowledge/subjects.yaml`,
    the same vocabulary the knowledge tree files under (SPECS.md O6b).
    `category:` was read and deleted with the move -- `facets.yaml` declares
    `subject` as `where: path`, so there is no field to disagree with the folder.
    """
    branches, subjects = _register()
    out: dict[tuple, list[dict]] = {}
    for p in sorted((root / "skills").rglob("SKILL.md")):
        rel = p.relative_to(root).as_posix()
        parts = rel.split("/")
        # A skill sits at a fixed depth; anything else is a tree that cannot be
        # rendered into routers without guessing which segment is the subject.
        if len(parts) != 5 or not rel.startswith("skills/"):
            problems.append(Problem(
                "warn", f"SKILL.md is not under skills/<branch>/<subject>/<name>/: "
                        f"{rel}", p))
            continue
        _, branch, subject, name, _ = parts
        fm = read_frontmatter(p)
        if not fm:
            problems.append(Problem("warn", f"no frontmatter, skipped: {p}", p))
            continue
        if branches and branch not in branches:
            problems.append(Problem(
                "warn", f"branch '{branch}' is not declared in subjects.yaml, "
                        f"skipped: {rel}", p))
            continue
        if subjects and subject not in subjects:
            problems.append(Problem(
                "warn", f"subject '{subject}' is not one of the subjects in "
                        f"subjects.yaml, skipped: {rel}", p))
            continue
        fm["_name"] = fm.get("name") or name
        fm["_path"] = rel
        fm["_branch"] = branch
        fm["_subject"] = subject
        # Default `model`: a skill that forgets to declare stays routable, which
        # is the pre-existing behaviour. Only an explicit `user` hides it.
        fm["_user"] = str(fm.get("invocation", "model")).strip() == "user"
        out.setdefault((branch, subject), []).append(fm)
    return out


def routed(skills: dict[tuple, list[dict]]) -> dict[tuple, list[dict]]:
    """Model-reachable skills only, subjects with none dropped.

    This is the whole enforcement of the user-invoked invariant: the routers
    index this, so a `user` skill is not merely unlisted, it is absent from
    every artifact the model ever reads.
    """
    out = {k: [f for f in v if not f["_user"]] for k, v in skills.items()}
    return {k: v for k, v in out.items() if v}


def user_invoked(skills: dict[tuple, list[dict]]) -> list[dict]:
    return sorted((f for v in skills.values() for f in v if f["_user"]),
                  key=lambda f: f["_name"])


def load_subjects(root: pathlib.Path) -> dict[tuple, dict]:
    """(branch, subject) -> the `_subject.md` prose beside the skills.

    The rename from `_category.md` is O6b's: the folder is a subject now, and a
    file named after a category in a subject folder is the vocabulary drift the
    move exists to remove.
    """
    return {(p.parent.parent.name, p.parent.name): read_frontmatter(p)
            for p in sorted((root / "skills").glob("*/*/_subject.md"))}


def origin_label(fm: dict) -> str:
    o, mode = fm.get("origin", "?"), fm.get("mode", "")
    # `mode: authored` on an `origin: authored` skill is the same fact twice.
    return f"{o} ({mode})" if mode and mode != o else o


# ── renderers ────────────────────────────────────────────────────────────
def render_branches_block(skills, branches=None) -> str:
    """Tier 0 names the three BRANCHES, never skills -- the same table
    `knowledge/CONTEXT.md` carries, and what keeps Tier 0 constant as the
    library grows.

    A branch with no skill is spelled WITHOUT the trailing slash, the trick
    `knowledge_index.render_branch_router` documents: a ticked `areas/` that is
    not a directory is a dead pointer this generator would be adding to
    `links --check`'s decision list every night.
    """
    branches = branches if branches is not None else _register()[0]
    counts: dict = {}
    for (branch, _subject), v in skills.items():
        counts[branch] = counts.get(branch, 0) + len(v)
    rows = ["| Branch | Descend when the task involves… | n |", "|---|---|---|"]
    for name in sorted(branches or counts):
        meta = branches.get(name)
        blurb = " ".join(meta.criteria.split()) if meta is not None \
            else "—"
        where = f"`{name}/`" if counts.get(name) else f"`{name}`"
        rows.append(f"| {where} | {blurb} | {counts.get(name, 0) or '—'} |")
    return "\n".join(rows)


def render_branch_router(branch: str, subjects: dict) -> str:
    """`skills/<branch>/CONTEXT.md` -- the subjects, from the register.

    Mirrors `knowledge_index.render_branch_router`: rows are the branch's
    SUBJECT folders, and a subject with no folder yet is listed as
    declared-and-empty rather than omitted. `publication` is in the register
    and absent from the disk, which is a fact about the tree.
    """
    branches, reg = _register()
    meta = branches.get(branch)
    name = meta.name if meta is not None else branch
    criteria = " ".join(meta.criteria.split()) if meta is not None else ""
    counts = {s: len(v) for (b, s), v in subjects.items() if b == branch}

    out = [f"# `{branch}/` — {name}", "", BANNER,
           f"<!-- LAYER 3 · {criteria} -->", "",
           "**This router triages the branch's subjects.** A skill is reached from "
           "here by descending into the subject folder it is filed under; the "
           "subject is the path, so there is no index of skills to read first.", "",
           "| Subject | | Falsified when | n |", "|---|---|---|---|"]
    for sid, s in reg.items():
        n = counts.get(sid, 0)
        crit = " ".join(s.criteria.split())
        where = f"`{sid}/`" if n else f"`{sid}`"
        out.append(f"| {where} | {s.name} | {crit} | {n or '—'} |")
    out += ["",
            f"{sum(counts.values())} skills in {len(counts)} of {len(reg)} "
            f"subjects. A subject folder appears on its first skill, so `—` means "
            f"declared and not yet written, never missing.", ""]
    return "\n".join(out)


def render_scopes_block(root: pathlib.Path) -> str:
    fm = read_frontmatter(root / "skills" / "_scope-bindings.md")
    rows = ["| Working directory | Branches |", "|---|---|"]
    for b in fm.get("bindings", []):
        glob, _, branches = b.partition("::")
        rows.append(f"| `{glob.strip()}` | {branches.strip()} |")
    return "\n".join(rows)


def render_subject_router(branch: str, subject: str, skills: list[dict], meta: dict) -> str:
    """`skills/<branch>/<subject>/CONTEXT.md` -- the subject's skills.

    The register's `name` and `criteria` lead, as they do in the knowledge
    tree's routers: a hand-written blurb is a description this generator would
    then be copying, and O3a made the register the source of both.
    """
    branches, reg = _register()
    smeta = reg.get(subject)
    title = f"`{branch}/{subject}/` — {smeta.name}" if smeta is not None \
        else f"`{branch}/{subject}/`"
    out = [f"# {title} — Tier 2 Router", "", BANNER, ""]
    if smeta is not None:
        out += [f"<!-- {subject}: {' '.join(smeta.criteria.split())} -->", ""]
    if meta.get("blurb"):
        out += [meta["blurb"], ""]
    out += ["| Skill | What it does | Origin | Trust |", "|---|---|---|---|"]
    # Stable order: trusted before trial, then alphabetical — the router should
    # read the way it should be searched.
    rank = {"trusted": 0, "trial": 1, "quarantine": 2, "deprecated": 3}
    for fm in sorted(skills, key=lambda f: (rank.get(f.get("trust", ""), 9), f["_name"])):
        out.append(f"| `{fm['_name']}` | {fm.get('description', '—')} "
                   f"| {origin_label(fm)} | {fm.get('trust', '?')} |")
    always = meta.get("always_on") or []
    if always:
        out += ["", "Always-on companions, loaded regardless of which skill fires:",
                ", ".join(f"`{a}`" for a in always) + "."]
    if meta.get("note"):
        out += ["", meta["note"]]
    return "\n".join(out) + "\n"


def render_triggers(cats) -> str:
    trig: dict[str, list[dict]] = {}
    anti: dict[str, list[dict]] = {}
    for name in sorted(cats):
        for fm in cats[name]:
            # `deprecated` = retained for provenance, never routed to
            # (skill-routing.md §Provenance and lifecycle). It stays in the
            # subject router so the record is discoverable; it must not be here.
            if fm.get("trust") == "deprecated":
                continue
            for t in fm.get("triggers", []):
                trig.setdefault(t.lower(), []).append(fm)
            for t in fm.get("antitriggers", []):
                anti.setdefault(t.lower(), []).append(fm)

    out = ["# Trigger Index", "", BANNER,
           "<!-- READ ON DEMAND. Never injected — it costs zero always-loaded"
           " tokens and may grow to any size. -->", "",
           "Resolution signal 3 ([[skill-routing]]). Match task",
           "vocabulary against the terms below; a match is **explainable** — you can name",
           "the term that fired, which an embedding similarity cannot.", "",
           "**An antitrigger match suppresses the skill even if a trigger also matched.**",
           "Check §Antitriggers before acting on a trigger hit.", "",
           f"{sum(len(v) for v in trig.values())} triggers and "
           f"{sum(len(v) for v in anti.values())} antitriggers over "
           f"{sum(len(v) for v in cats.values())} skills.", "",
           "## Triggers", "", "| Term | Skill | Subject | Trust |", "|---|---|---|---|"]
    for term in sorted(trig):
        for fm in sorted(trig[term], key=lambda f: f["_name"]):
            out.append(f"| {term} | `{fm['_name']}` | {fm['_subject']} "
                       f"| {fm.get('trust', '?')} |")
    out += ["", "## Antitriggers", "", "| Term | Suppresses |", "|---|---|"]
    for term in sorted(anti):
        out.append(f"| {term} | " + ", ".join(f"`{f['_name']}`" for f in
                                              sorted(anti[term], key=lambda f: f["_name"])) + " |")

    collisions = sorted(t for t, v in trig.items() if len(v) > 1)
    out += ["", "## Ambiguous terms", ""]
    out += ([f"- `{t}` → " + ", ".join(f"`{f['_name']}`" for f in trig[t]) for t in collisions]
            or ["None — every trigger term selects exactly one skill."])
    out += ["", "A term that selects more than one skill cannot resolve at signal 3 alone;",
            "fall through to a subject browse, or tighten the trigger vocabulary.", ""]
    return "\n".join(out)


def body_path(fm: dict) -> str:
    """Where the instructions actually live: upstream for `link`, here otherwise."""
    up = fm.get("upstream_path")
    return f"{up}/SKILL.md" if fm.get("mode") == "link" and up else f"{roots.tilde(roots.MEMORY)}/{fm['_path']}"


def render_user_index(users: list[dict]) -> str:
    """Human-facing list of the slash commands. Not a router: the model has no
    business reading it, and nothing points here from `CONTEXT.md`."""
    out = ["# User-invoked skills", "", BANNER,
           "<!-- FOR THE HUMAN. These skills are reachable ONLY by typing their",
           "     command. They appear in no router and in no trigger index. -->", "",
           "Resolution signal 1 ([[skill-routing]]). Each row is",
           "generated into `~/.claude/commands/` and `~/.config/opencode/command/`, so the",
           "same `/name` works in both harnesses.", "",
           f"{len(users)} commands.", "",
           "| Command | What it does | Subject | Trust |", "|---|---|---|---|"]
    for fm in users:
        out.append(f"| `/{fm['_name']}` | {fm.get('description', '—')} "
                   f"| {fm['_subject']} | {fm.get('trust', '?')} |")
    out += ["", "Regenerate after adding one: `familiar skills index`.", ""]
    return "\n".join(out)


def render_command(fm: dict, bodies: dict[str, str], claude: bool) -> str:
    """One slash command. A POINTER, never a copy — copying the body here would
    fork it from upstream on the first `git pull`."""
    head = [f"description: {fm.get('description', fm['_name'])}"]
    if fm.get("argument_hint"):
        head.append(f"argument-hint: {fm['argument_hint']}")
    if claude:
        # The whole point: keep the SlashCommand tool from reaching it, so this
        # stays human-only in Claude Code exactly as it is in opencode.
        head.append("disable-model-invocation: true")

    out = ["---", *head, "---", "",
           CMD_BANNER.format(path=fm["_path"]), "",
           f"Read `{body_path(fm)}` and follow it."]

    # Upstream assumes its whole set is installed as harness skills. Ours are
    # not (zero-install), so any "call the Skill tool with X" it contains has to
    # be resolved by path. Emit the mapping rather than leaving it to guesswork.
    refs = [(n, bodies[n]) for n in fm.get("related", []) if n in bodies]
    if refs:
        out += ["",
                "That file may tell you to **call the Skill tool** with another skill by name, or",
                "name it as `/skill`. Canonical skills are not installed in any harness",
                "([[skill-routing]] §Zero-install), so there",
                "is nothing to call. Read the file instead:", ""]
        out += [f"- `{n}` → `{b}`" for n, b in refs]
        out += ["", f"A name not in that list: find it under `{roots.tilde(roots.SKILLS)}/*/*/<name>/SKILL.md`.",
                "If it is not there, it was not adopted — say so rather than improvising it."]

    out += ["", "$ARGUMENTS", ""]
    return "\n".join(out)


def plan_commands(users: list[dict], bodies: dict[str, str], homes):
    """[(path, content)] for every harness home that exists. Absent home = skipped."""
    planned = []
    for _, dest, claude in homes:
        if not dest.parent.exists():
            continue
        for fm in users:
            planned.append((dest / f"{fm['_name']}.md", render_command(fm, bodies, claude)))
    return planned


def stale_commands(users: list[dict], homes):
    """Generated command files whose skill is gone. Only ever OUR files: a
    hand-written command carries no banner and is never touched."""
    keep = {f"{fm['_name']}.md" for fm in users}
    out = []
    for _, dest, _c in homes:
        if not dest.exists():
            continue
        for f in sorted(dest.glob("*.md")):
            if f.name not in keep and OURS.search(f.read_text()):
                out.append(f)
    return out


def replace_block(text: str, tag: str, content: str) -> str | None:
    """None when the marker is absent -- the caller records a problem. This used
    to `raise SystemExit`, which is not an `Exception` and so escaped the pass's
    per-stage guard: one missing marker skipped the report and the commit.

    Not `engine/lib/generated_block.splice`, on purpose: this substitutes into
    an EXISTING, named marker pair among several in one file and errors when
    it's missing; that module strips every stale block from a file with at
    most one and appends fresh when none is found. See its docstring."""
    pat = re.compile(rf"(<!-- BEGIN:{tag} \(generated\) -->\n).*?(\n<!-- END:{tag} -->)", re.S)
    if not pat.search(text):
        return None
    return pat.sub(lambda m: m.group(1) + content + m.group(2), text)


# ── planning ─────────────────────────────────────────────────────────────
def plan(root: pathlib.Path = None, homes=None) -> Plan:
    """Decide everything; write nothing. The only entry point that matters."""
    root = pathlib.Path(root or DEFAULT_ROOT)
    homes = HARNESS_COMMANDS if homes is None else homes
    skills_dir = root / "skills"
    problems: list[Problem] = []

    cats = load_skills(root, problems)
    catmeta = load_subjects(root)
    for key in cats:
        if key not in catmeta:
            problems.append(Problem(
                "error", f"no _subject.md for '{key[1]}' — router prose would be "
                         f"lost", skills_dir / key[0] / key[1]))

    # The split that everything below rests on. `rcats` is what the model may
    # see; `users` is what only the human may reach.
    rcats = routed(cats)
    users = user_invoked(cats)
    if any(p.level == "error" for p in problems):
        # Nothing below can be rendered correctly -- a subject whose prose is
        # missing would be rendered as a subject without prose, and the router
        # would lose it. Stop here, exactly as the old `return 1` did, before
        # anything could be written.
        return Plan(root=root, writes=[], stale=[], problems=problems,
                    routed=rcats, users=users)
    bodies = {f["_name"]: body_path(f) for v in rcats.values() for f in v}

    writes: list = []
    tier0 = skills_dir / "CONTEXT.md"
    try:
        t0 = tier0.read_text()
    except OSError as exc:
        t0 = None
        problems.append(Problem("error", f"Tier 0 router unreadable: {exc}", tier0))
    for tag, content in ((BRANCH_TAG, render_branches_block(rcats)),
                         ("SCOPES", render_scopes_block(root))):
        if t0 is None:
            break
        t0 = replace_block(t0, tag, content)
        if t0 is None:
            problems.append(Problem(
                "error", f"marker BEGIN:{tag} not found in the Tier 0 router; it "
                         f"cannot be regenerated until the marker is restored", tier0))
    if t0 is not None:
        writes.append((tier0, t0))
        for branch in sorted({b for b, _ in rcats}):
            writes.append((skills_dir / branch / "CONTEXT.md",
                           render_branch_router(branch, rcats)))
        for (branch, subject), skills in rcats.items():
            writes.append((skills_dir / branch / subject / "CONTEXT.md",
                           render_subject_router(branch, subject, skills,
                                                 catmeta[(branch, subject)])))
        writes.append((skills_dir / "TRIGGERS.md", render_triggers(rcats)))
        writes.append((skills_dir / "USER-INVOKED.md", render_user_index(users)))

        # Never clobber a command we did not write. `~/.claude/commands/` is the
        # human's directory first; a hand-written file there outranks this
        # generator.
        for path, body in plan_commands(users, bodies, homes):
            if path.exists() and not OURS.search(path.read_text()):
                problems.append(Problem(
                    "warn", f"not ours, left alone: {path} — rename the skill or "
                            f"the command", path))
                continue
            writes.append((path, body))

    tier0_chars = len(t0) if t0 else 0
    if tier0_chars >= TIER0_BUDGET:
        # A content problem only a human can fix, by moving skills out of Tier 0.
        # Still written: a STALE router is worse than an oversized one, and the
        # healthcheck would flag drift forever.
        problems.append(Problem(
            "warn", f"Tier 0 is {tier0_chars} chars, over the {TIER0_BUDGET} budget "
                    f"— it must name branches, never skills", tier0))

    if any(p.level == "error" for p in problems):
        writes = []                # cannot render correctly: write nothing

    return Plan(root=root, writes=writes,
                stale=[] if not writes else stale_commands(users, homes),
                problems=problems, routed=rcats, users=users,
                tier0_chars=tier0_chars)


# ── CLI ──────────────────────────────────────────────────────────────────
def main(argv=None) -> int:
    """A thin adapter over `plan`. Healthcheck depends on these exit codes:
    0 ok, 1 error, 3 drift under --check."""
    ap = argparse.ArgumentParser(prog="familiar skills index")
    ap.add_argument("--check", action="store_true",
                    help="report drift and exit 3; write nothing")
    args = ap.parse_args(argv if argv is not None else sys.argv[1:])

    p = plan()
    for prob in p.problems:
        if prob.level != "note":
            print(f"!! {prob.what}", file=sys.stderr)
    if p.failed:
        return 1

    drift, stale = p.drift, p.stale
    if args.check:
        for path in drift:
            print(f"DRIFT {path}" if not path.is_relative_to(p.root)
                  else f"DRIFT {path.relative_to(p.root)}")
        for path in stale:
            print(f"STALE {path}")
        print(f"{len(drift)} of {len(p.writes)} generated files would change, "
              f"{len(stale)} stale")
        return 3 if (drift or stale) else 0

    p.apply()

    nr = sum(len(v) for v in p.routed.values())
    nsub = len({(f["_branch"], f["_subject"]) for v in p.routed.values() for f in v})
    print(f"skills index: {nr} routed skills in {nsub} subjects, "
          f"{len(p.users)} user-invoked")
    print(f"  Tier 0  {(p.root / 'skills/CONTEXT.md').relative_to(p.root)}  "
          f"{p.tier0_chars} chars "
          f"({'OK' if p.tier0_chars < TIER0_BUDGET else 'OVER BUDGET'}, "
          f"budget {TIER0_BUDGET})")
    for branch in sorted({b for b, _ in p.routed}):
        print(f"  Tier 1  skills/{branch}/CONTEXT.md")
    for branch, subject in sorted(p.routed):
        print(f"  Tier 2  skills/{branch}/{subject}/CONTEXT.md")
    print(f"  index   skills/TRIGGERS.md")
    print(f"  index   skills/USER-INVOKED.md  (human-facing; not a router)")
    for label, dest, _c in HARNESS_COMMANDS:
        here = [w for w, _ in p.writes if w.parent == dest]
        print(f"  cmds    {label:<12} {dest}  "
              f"{len(here) if here else 'skipped (no harness home)'}"
              + (" commands" if here else ""))
    print(f"  rewritten: {len(drift)}"
          + (f", removed {len(stale)} stale" if stale else ""))
    if p.tier0_chars >= TIER0_BUDGET:
        return 1
    return 0


# ── stage entry point ────────────────────────────────────────────────────
def run(ctx) -> bool:
    """Stage 7 of the pass. Derived artifacts: regenerate, never hand-edit."""
    p = plan(ctx.agents)
    for prob in p.problems:
        ctx.note("7", prob.what, prob.level)

    if p.failed:
        ctx.note("7", "routers and TRIGGERS.md were NOT regenerated — they still "
                      "describe the tree as it was before tonight", "error")
    elif ctx.dry_run:
        if p.drift or p.stale:
            ctx.note("7", f"{len(p.drift)} generated file(s) have drifted from "
                          f"frontmatter and {len(p.stale)} are stale; a real run "
                          f"would regenerate them")
    else:
        # Only claim a change when bytes actually changed. A report that lists
        # work the pass did not do is a report that stops being read, and this
        # stage rewrites identical content on most nights.
        changed = p.apply()
        if changed:
            ctx.act("7", ", ".join(sorted(c.name for c in changed[:4]))
                    + (f" and {len(changed) - 4} more" if len(changed) > 4 else ""),
                    f"regenerated {len(changed)} file(s) from frontmatter")
    return True
